use simple_logger::SimpleLogger;
use split_include::Autoconf;
use std::env::current_exe;
use std::fs::{read_to_string, write};
use std::io;
use tempfile::tempdir;

#[test]
fn split() -> io::Result<()> {
    SimpleLogger::new().init().ok();

    let tmp = tempdir()?;

    let mut autoconf_h = tmp.path().to_path_buf();
    autoconf_h.push("autoconf.h");
    write(
        autoconf_h,
        r#"/* Generated configuration */
#ifndef AUTOCONF_H
#define AUTOCONF_H

/* Feature A */
#define CONFIG_FEATUREA_OPTION1 1
#undef CONFIG_FEATUREA_OPTION2

/* Feature B */
#undef CONFIG_FEATUREB_OPTION3
#define CONFIG_FEATUREB_OPTION4 2

#endif /* !defined AUTOCONF_H */
"#,
    )?;

    let autoconf = Autoconf::load(&tmp);
    autoconf.gen_py(&tmp);
    autoconf.gen_pl(&tmp);
    autoconf.gen_h(&tmp);
    autoconf.gen_inc(&tmp);

    let mut autoconf_py = tmp.path().to_path_buf();
    autoconf_py.push("autoconf.py");
    let bin = current_exe()?;
    let bin = bin.to_string_lossy();
    assert_eq!(
        read_to_string(autoconf_py)?,
        format!(
            r#"# coding: utf-8
# File generated by “{}” from “autoconf.h”

OPTION1 = 1
OPTION2 = False
OPTION3 = False
OPTION4 = 2
"#,
            bin
        )
    );

    let mut autoconf_pl = tmp.path().to_path_buf();
    autoconf_pl.push("autoconf.pl");
    assert_eq!(
        read_to_string(autoconf_pl)?,
        format!(
            r#"# File generated by “{}” from “autoconf.h”

$OPTION1 = 1;
$OPTION2 = 0;
$OPTION3 = 0;
$OPTION4 = 2;

1;
"#,
            bin
        )
    );

    let mut featurea_h = tmp.path().to_path_buf();
    featurea_h.push("config.featurea.h");
    assert_eq!(
        read_to_string(featurea_h)?,
        format!(
            r#"/* File generated by “{}” from “autoconf.h” */
#ifndef AUTOCONF_FEATUREA_H
#define AUTOCONF_FEATUREA_H

#define OPTION1 1
#undef OPTION2

#endif /* !defined AUTOCONF_FEATUREA_H */
"#,
            bin
        )
    );

    let mut featureb_h = tmp.path().to_path_buf();
    featureb_h.push("config.featureb.h");
    assert_eq!(
        read_to_string(featureb_h)?,
        format!(
            r#"/* File generated by “{}” from “autoconf.h” */
#ifndef AUTOCONF_FEATUREB_H
#define AUTOCONF_FEATUREB_H

#undef OPTION3
#define OPTION4 2

#endif /* !defined AUTOCONF_FEATUREB_H */
"#,
            bin
        )
    );

    let mut featurea_inc = tmp.path().to_path_buf();
    featurea_inc.push("config.featurea.inc");
    assert_eq!(
        read_to_string(featurea_inc)?,
        format!(
            r#"; File generated by “{}” from “autoconf.h”

OPTION1 EQU 1
OPTION2 EQU 0

    END
"#,
            bin
        )
    );

    let mut featureb_inc = tmp.path().to_path_buf();
    featureb_inc.push("config.featureb.inc");
    assert_eq!(
        read_to_string(featureb_inc)?,
        format!(
            r#"; File generated by “{}” from “autoconf.h”

OPTION3 EQU 0
OPTION4 EQU 2

    END
"#,
            bin
        )
    );

    Ok(())
}
